"use client";

import { useEffect, useRef, useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "@/lib/supabase/client";

function CodeForm({
  factorId,
  submitLabel,
}: {
  factorId: string;
  submitLabel: string;
}) {
  const router = useRouter();
  const [code, setCode] = useState("");
  const [error, setError] = useState(false);
  const [busy, setBusy] = useState(false);

  async function onSubmit(event: React.FormEvent) {
    event.preventDefault();
    setBusy(true);
    setError(false);
    const supabase = createClient();
    const { error } = await supabase.auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
    setBusy(false);
    if (error) {
      setError(true);
      return;
    }
    router.replace("/");
    router.refresh();
  }

  return (
    <form onSubmit={onSubmit} className="mt-6 space-y-5">
      {error && (
        <p role="alert" className="alert">
          That code didn&apos;t work. Codes change every 30 seconds, so try the newest one.
        </p>
      )}
      <div>
        <label htmlFor="code" className="mb-1 block font-medium text-ink">
          6-digit code
        </label>
        <input
          id="code"
          name="code"
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="[0-9]{6}"
          maxLength={6}
          required
          value={code}
          onChange={(e) => setCode(e.target.value)}
          className="text-input tracking-widest"
        />
      </div>
      <button type="submit" className="btn-primary w-full" disabled={busy}>
        {busy ? "Checking…" : submitLabel}
      </button>
    </form>
  );
}

export function MfaVerify({ factorId }: { factorId: string }) {
  return <CodeForm factorId={factorId} submitLabel="Continue" />;
}

type Enrollment = { factorId: string; qrCode: string; secret: string };

export function MfaEnroll() {
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [failed, setFailed] = useState(false);
  const started = useRef(false);

  useEffect(() => {
    // Only start one enrolment, even when React runs effects twice in development.
    if (started.current) return;
    started.current = true;

    async function start() {
      const supabase = createClient();

      // Clear any half-finished set-up from an earlier visit.
      const { data: factors } = await supabase.auth.mfa.listFactors();
      for (const factor of factors?.all ?? []) {
        if (factor.status === "unverified") {
          await supabase.auth.mfa.unenroll({ factorId: factor.id });
        }
      }

      const { data, error } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: "Authenticator app",
      });
      if (error || !data) {
        setFailed(true);
        return;
      }
      setEnrollment({ factorId: data.id, qrCode: data.totp.qr_code, secret: data.totp.secret });
    }

    start();
  }, []);

  if (failed) {
    return (
      <p role="alert" className="alert mt-6">
        Two-factor set-up couldn&apos;t start. Please refresh the page to try again.
      </p>
    );
  }

  if (!enrollment) return <p className="mt-6 text-ink">Preparing…</p>;

  return (
    <div className="mt-6">
      <ol className="list-decimal space-y-2 pl-5 text-ink">
        <li>Install an authenticator app on your phone, such as Google Authenticator or Microsoft Authenticator.</li>
        <li>In the app, add an account and scan this QR code.</li>
        <li>Enter the 6-digit code the app shows.</li>
      </ol>
      {/* The QR code is a data URL generated by Supabase, so next/image isn't needed. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src={enrollment.qrCode}
        alt="QR code to scan with your authenticator app"
        width={200}
        height={200}
        className="mx-auto mt-6 rounded-lg bg-white p-2"
      />
      <p className="mt-4 text-sm text-ink">
        Can&apos;t scan? Enter this key in the app instead:{" "}
        <code className="break-all rounded bg-muted px-1">{enrollment.secret}</code>
      </p>
      <CodeForm factorId={enrollment.factorId} submitLabel="Turn on two-factor" />
    </div>
  );
}
